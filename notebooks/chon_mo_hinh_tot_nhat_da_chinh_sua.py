# ----------------------------------------------------------------------
models = {
    "SVM": LinearSVC(C=1.0, random_state=RANDOM_STATE),
    "Logistic Regression": LogisticRegression(
        C=1.0, max_iter=1000, random_state=RANDOM_STATE, n_jobs=-1
    ),
    "Naive Bayes": MultinomialNB(alpha=1.0),
    "KNN": KNeighborsClassifier(n_neighbors=11, metric="cosine", n_jobs=-1),
    "Decision Tree": DecisionTreeClassifier(
        max_depth=20, random_state=RANDOM_STATE
    ),
    "Random Forest": RandomForestClassifier(
        n_estimators=100, max_depth=20, random_state=RANDOM_STATE, n_jobs=-1
    ),
}

