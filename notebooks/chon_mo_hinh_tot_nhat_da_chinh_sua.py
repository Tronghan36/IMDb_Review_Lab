"""## Phương án 3 — Soft Voting"""

"""
Phương án 3: Soft Voting trên IMDB Dataset
- Lấy trung bình có trọng số Xác SUẤT lớp positive của 3 mô hình thành phần:
  Logistic Regression + Multinomial Naive Bayes + Random Forest, tỉ lệ 2 : 1 : 1
- Gán nhãn bằng cách so sánh xác suất trung bình với ngưỡng 0,5
- Có đối chứng: trọng số đều 1 : 1 : 1
- Biểu đồ: (1) so sánh các mô hình thành phần với Soft Voting, (2) đường ROC

Chạy:  python phuong_an_3_soft_voting.py
Cần:   pip install pandas numpy scikit-learn matplotlib seaborn
Nếu có sẵn ket_qua_phuong_an_2.csv (Phương án 2) thì thêm cột XGBoost vào biểu đồ.
"""
import os
import re
import time

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.ensemble import RandomForestClassifier
from sklearn.feature_extraction.text import ENGLISH_STOP_WORDS, TfidfVectorizer
