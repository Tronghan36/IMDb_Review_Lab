def eval_model(name, model, grid=None):
    """Huấn luyện (có thể tìm siêu tham số 3-fold) rồi đánh giá trên tập Test."""
    t = time.time()
    if grid and TUNE_BASELINE:
        model = GridSearchCV(model, grid, scoring="f1", cv=cv, n_jobs=-1)
    model.fit(X_train_vec, y_train)
    pred = model.predict(X_test_vec)
    score = (model.predict_proba(X_test_vec)[:, 1]
             if hasattr(model, "predict_proba")
             else model.decision_function(X_test_vec))
    print(f"  {name:<20} xong sau {time.time() - t:6.1f}s")
    return {
        "Model": name,
        "Accuracy": accuracy_score(y_test, pred),
        "Precision": precision_score(y_test, pred),
        "Recall": recall_score(y_test, pred),
        "F1-Score": f1_score(y_test, pred),
        "AUC (ROC)": roc_auc_score(y_test, score),
    }


