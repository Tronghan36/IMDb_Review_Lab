# ----------------------------------------------------------------------
if not os.path.exists(CSV_PATH):
    raise FileNotFoundError(
        f"Không tìm thấy file '{CSV_PATH}'. Hãy đặt 'IMDB Dataset.csv' "
        "vào cùng thư mục với file code.")

def load_imdb(path):
    """Đọc IMDB Dataset.csv. Nếu pandas làm rơi nhiều dòng (file có dấu ngoặc
    kép không khớp) thì dùng cách đọc dự phòng bằng regex. KHÔNG dùng
    quoting=csv.QUOTE_NONE vì sẽ làm mất gần hết dữ liệu."""
    try:
        d = pd.read_csv(path, on_bad_lines="skip")
    except pd.errors.ParserError:
        d = pd.read_csv(path, on_bad_lines="skip", engine="python")
    if len(d) >= 45000:            # file gốc có 50.000 dòng
        return d
    print(f"Cảnh báo: pandas chỉ đọc được {len(d):,} dòng -> thử cách đọc dự phòng...")
    text = open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")
    body = text.split("\n", 1)[1]                 # bỏ dòng tiêu đề
    if not body.endswith("\n"):
        body += "\n"
    rows = []
    for review, label in re.findall(r"(.*?),(positive|negative)\n", body, flags=re.S):
        review = review.strip()
        if len(review) >= 2 and review[0] == '"' and review[-1] == '"':
            review = review[1:-1].replace('""', '"')
        rows.append((review, label))
    fb = pd.DataFrame(rows, columns=["review", "sentiment"])
    print(f"Cách đọc dự phòng: {len(fb):,} dòng")
    return fb if len(fb) > len(d) else d


df = load_imdb(CSV_PATH).drop_duplicates()
