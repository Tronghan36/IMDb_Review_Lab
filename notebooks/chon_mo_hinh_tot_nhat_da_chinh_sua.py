# ----------------------------------------------------------------------
# 4. Soft Voting = trung bình có trọng số xác suất, rồi so với ngưỡng 0,5
#    (tương đương VotingClassifier(voting="soft", weights=[2, 1, 1]))
# ----------------------------------------------------------------------
P = np.column_stack([probs[n] for n in components])      # (n_test, 3)


def soft_vote(weights):
    w = np.asarray(weights, dtype=float)
    return P @ (w / w.sum())


def evaluate(name, prob):
    pred = (prob >= THRESHOLD).astype(int)
    return {
        "Model": name,
        "Accuracy": accuracy_score(y_test, pred),
        "Precision": precision_score(y_test, pred),
        "Recall": recall_score(y_test, pred),
        "F1-Score": f1_score(y_test, pred),
        "AUC (ROC)": roc_auc_score(y_test, prob),
    }


vote_prob = soft_vote(WEIGHTS)
equal_prob = soft_vote([1, 1, 1])

rows = [evaluate(n, probs[n]) for n in components]
rows.append(evaluate("Soft Voting (2:1:1)", vote_prob))
rows.append(evaluate("Soft Voting (1:1:1)", equal_prob))   # đối chứng

# Thời gian huấn luyện của Soft Voting = tổng 3 mô hình thành phần
