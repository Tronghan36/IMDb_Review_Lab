def load_imdb(path):
  """Đọc IMDB Dataset.csv. Nếu pandas làm rơi nhiều dòng thì dùng cách đọc dự phòng bằng regex."""
  try:
    d = pd.read_csv(path, on_bad_lines="skip")
  except pd.errors.ParserError:
    d = pd.read_csv(path, on_bad_lines="skip", engine="python")
  if len(d) >= 45000:
    return d
  print(
      f"Cảnh báo: pandas chỉ đọc được {len(d):,} dòng -> thử cách đọc dự"
      " phòng..."
  )
  text = open(path, encoding="utf-8", errors="replace").read().replace("\r\n", "\n")
  body = text.split("\n", 1)[1]
  if not body.endswith("\n"):
    body += "\n"
  rows = []
  for review, label in re.findall(
      r"(.*?),(positive|negative)\n", body, flags=re.S
  ):
    review = review.strip()
    if len(review) >= 2 and review[0] == '"' and review[-1] == '"':
      review = review[1:-1].replace('""', '"')
    rows.append((review, label))
  fb = pd.DataFrame(rows, columns=["review", "sentiment"])
  print(f"Cách đọc dự phòng: {len(fb):,} dòng")
  return fb if len(fb) > len(d) else d


print(f"Đang đọc dữ liệu từ: {CSV_PATH}")
df = load_imdb(CSV_PATH).drop_duplicates()
df["label"] = (df["sentiment"] == "positive").astype(int)

# Giữ lại các từ phủ định quan trọng
NEGATIONS = {
    "no",
    "not",
    "nor",
    "never",
    "none",
    "nobody",
    "nothing",
    "neither",
    "nowhere",
    "cannot",
    "without",
    "hardly",
}
STOPWORDS = set(ENGLISH_STOP_WORDS) - NEGATIONS


def clean_text(text: str) -> str:
  text = re.sub(r"<.*?>", " ", str(text))  # Bỏ thẻ HTML
  text = text.lower()
  text = re.sub(r"n't\b", " not", text)  # Biến don't -> do not
  text = re.sub(r"[^a-z\s]", " ", text)  # Chỉ giữ lại chữ cái
  tokens = [w for w in text.split() if w not in STOPWORDS]
  return " ".join(tokens)


print("Đang làm sạch văn bản...")
df["clean"] = df["review"].apply(clean_text)

# Chia tập Train/Test 80:20 phân tầng
X_train, X_test, y_train, y_test = train_test_split(
    df["clean"],
    df["label"],
    test_size=0.2,
    stratify=df["label"],
    random_state=RANDOM_STATE,
)
print(f"Kích thước Train: {len(X_train):,} | Test: {len(X_test):,}")

# Trích xuất đặc trưng TF-IDF (Unigram + Bigram)
print("Đang trích xuất đặc trưng TF-IDF (max_features=50,000)...")
tfidf = TfidfVectorizer(ngram_range=(1, 2), max_features=50000, min_df=3)
X_train_vec = tfidf.fit_transform(X_train)
X_test_vec = tfidf.transform(X_test)


# ----------------------------------------------------------------------
# 2. Xây dựng lớp Mô hình NB-SVM (Naive Bayes + Support Vector Machine)
# ----------------------------------------------------------------------
class NBSVMClassifier:

  def __init__(self, alpha=1.0, C=2.0, max_iter=1000, random_state=42):
    self.alpha = alpha
    self.C = C
    self.max_iter = max_iter
    self.random_state = random_state
    self.r = None
    self.model = None

  def _compute_log_count_ratio(self, X, y):
    """Tính tỉ số log-count ratio r của Naive Bayes"""
    X_bin = (X > 0).astype(np.float64)

    p = self.alpha + X_bin[y == 1].sum(axis=0)
    q = self.alpha + X_bin[y == 0].sum(axis=0)

    p_norm = p / np.abs(p).sum()
    q_norm = q / np.abs(q).sum()

    self.r = np.log(p_norm / q_norm)
    self.r = np.asarray(self.r).reshape(-1)

  def fit(self, X, y):
    # 1. Tính vector tỉ số r từ tập Train
    self._compute_log_count_ratio(X, y)

    # 2. Nhân ma trận đặc trưng X với vector r
    r_diag = diags(self.r)
    X_nb = X.dot(r_diag)

    # 3. Huấn luyện mô hình tuyến tính Logistic Regression trên X_nb
    self.model = LogisticRegression(
        C=self.C,
        max_iter=self.max_iter,
        random_state=self.random_state,
        n_jobs=-1,
    )
    self.model.fit(X_nb, y)
    return self

  def predict(self, X):
    r_diag = diags(self.r)
    X_nb = X.dot(r_diag)
    return self.model.predict(X_nb)

  def predict_proba(self, X):
    r_diag = diags(self.r)
    X_nb = X.dot(r_diag)
    return self.model.predict_proba(X_nb)


# ----------------------------------------------------------------------
# 3. Huấn luyện và Đánh giá Mô hình NB-SVM
# ----------------------------------------------------------------------
print("\nĐang huấn luyện mô hình NB-SVM...")
nbsvm = NBSVMClassifier(alpha=1.0, C=2.0, random_state=RANDOM_STATE)

t0 = time.time()
nbsvm.fit(X_train_vec, y_train.values)
train_time = time.time() - t0
print(f"Huấn luyện NB-SVM hoàn tất sau: {train_time:.2f} giây")

# Dự đoán trên tập Test
y_pred = nbsvm.predict(X_test_vec)
y_prob = nbsvm.predict_proba(X_test_vec)[:, 1]

# Tính toán các chỉ số
nbsvm_row = {
    "Model": "NB-SVM",
    "Accuracy": accuracy_score(y_test, y_pred),
    "Precision": precision_score(y_test, y_pred),
    "Recall": recall_score(y_test, y_pred),
    "F1-Score": f1_score(y_test, y_pred),
    "AUC (ROC)": roc_auc_score(y_test, y_prob),
}

print("\n===== KẾT QUẢ MÔ HÌNH NB-SVM TRÊN TẬP TEST =====")
for k, v in nbsvm_row.items():
  print(f"  {k:<10}: {v if k == 'Model' else round(v, 4)}")

# Lưu kết quả ra file CSV
pd.DataFrame([nbsvm_row]).to_csv("ket_qua_phuong_an_5.csv", index=False)

