# 4. Huấn luyện & Đánh giá
# ----------------------------------------------------------------------
rows = []
print("\n===== ĐANG HUẤN LUYỆN 6 MÔ HÌNH BASELINE =====")
for name, model in models.items():
  t0 = time.time()
  model.fit(X_train_vec, y_train)
  y_pred = model.predict(X_test_vec)

  if hasattr(model, "predict_proba"):
    score = model.predict_proba(X_test_vec)[:, 1]
  elif hasattr(model, "decision_function"):
    score = model.decision_function(X_test_vec)
  else:
    score = y_pred

  row = {
      "Model": name,
      "Accuracy": accuracy_score(y_test, y_pred),
      "Precision": precision_score(y_test, y_pred),
      "Recall": recall_score(y_test, y_pred),
      "F1-Score": f1_score(y_test, y_pred),
      "AUC (ROC)": roc_auc_score(y_test, score),
  }
  rows.append(row)
  print(
      f"  {name:<20} xong sau {time.time() - t0:5.1f}s | Acc:"
      f" {row['Accuracy']:.4f}"
  )

results = pd.DataFrame(rows)
print("\n BẢNG KẾT QUẢ CÁC MÔ HÌNH BASELINE:")
print(results.round(4).to_string(index=False))

